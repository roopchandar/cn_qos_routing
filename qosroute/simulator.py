"""Discrete-time, packet-level network simulator.

Time model
----------
The clock advances in ticks of 1 ms. In every tick, in this order:

1. Link events (bandwidth degradation) are applied.
2. The router's ``on_tick`` hook runs (e.g. the heuristic refreshes link costs).
3. Packets whose propagation finishes this tick arrive at their next router.
   Packets that reached their destination are *delivered*.
4. New packets are generated by every flow (Poisson arrivals).
5. Every packet sitting at a router asks the routing algorithm for a next hop
   (one batched call). The packet is appended to that link's output queue, or
   *dropped* if the queue is full (tail-drop) or its hop budget (TTL) is spent.
6. Every directed link transmits packets from the head of its FIFO queue using
   a byte-credit scheduler (bandwidth in bytes/ms). A transmitted packet arrives
   at the far end after the link's propagation delay.
7. Statistics are sampled.

So a packet's end-to-end delay = queueing + transmission + propagation delays,
measured with 1 ms resolution.

Important: this is a *simulation*. It models finite FIFO queues, bandwidth,
propagation delay, tail-drop and TTL, but not TCP congestion control, routing
protocol message overhead, MAC/PHY effects, or packet reordering costs.
"""
from __future__ import annotations

from collections import Counter, defaultdict, deque
from dataclasses import dataclass

import networkx as nx
import numpy as np

from .topology import mbps_to_bytes_per_ms, neighbor_table, hop_distances, prop_distances
from .traffic import PKT_MAX_BYTES, PKT_MIN_BYTES, Scenario

DEFAULT_TTL = 12        # maximum hops before a packet is discarded (loop guard)
CONGESTED_OCC = 0.8     # a queue >= 80 % full counts as "congested"


class Packet:
    __slots__ = ("pid", "flow", "src", "dst", "size", "t_created", "node", "hops",
                 "visited", "path", "t_decision", "rl_state", "rl_action", "rl_penalty")

    def __init__(self, pid, flow, src, dst, size, t):
        self.pid = pid
        self.flow = flow
        self.src = src
        self.dst = dst
        self.size = size
        self.t_created = t
        self.node = src
        self.hops = 0
        self.visited = 1 << src          # bitmask of routers already visited
        self.path = [src]
        self.t_decision = t              # used by the DQN for per-hop delay
        self.rl_state = None             # DQN bookkeeping (state, action, penalty)
        self.rl_action = None
        self.rl_penalty = 0.0


class Link:
    """One direction of a full-duplex link with its own FIFO output queue."""

    __slots__ = ("u", "v", "bw_nominal", "bw", "prop", "cap", "queue", "queue_bytes",
                 "credit", "tx_bytes", "bw_sum", "drops", "drop_ema", "util_ema",
                 "occ_sum", "congested_ticks", "tick_tx")

    def __init__(self, u, v, bw_mbps, prop, cap):
        self.u, self.v = u, v
        self.bw_nominal = mbps_to_bytes_per_ms(bw_mbps)
        self.bw = self.bw_nominal         # current bytes per ms (events may reduce it)
        self.prop = int(prop)
        self.cap = int(cap)
        self.queue: deque = deque()
        self.queue_bytes = 0
        self.credit = 0.0
        self.tx_bytes = 0                 # bytes transmitted during the traffic window
        self.bw_sum = 0.0                 # bytes that *could* have been sent in that window
        self.drops = 0
        self.drop_ema = 0.0               # recent drop indicator (exp. moving average)
        self.util_ema = 0.0               # recent utilisation (exp. moving average)
        self.occ_sum = 0.0
        self.congested_ticks = 0
        self.tick_tx = 0

    @property
    def occupancy(self) -> float:
        return len(self.queue) / self.cap

    @property
    def queue_delay_ms(self) -> float:
        """Estimated time to drain the current backlog."""
        return self.queue_bytes / self.bw if self.bw > 0 else 1e3


@dataclass
class Snapshot:
    t: int
    occupancy: dict          # (u, v) -> queue occupancy in [0, 1]
    utilization: dict        # (u, v) -> utilisation over the last window
    load: float


class Simulator:
    def __init__(self, graph: nx.Graph, scenario: Scenario, router, ttl: int = DEFAULT_TTL,
                 snapshot_every: int = 0, track_paths: bool = True):
        self.g = graph
        self.scenario = scenario
        self.router = router
        self.ttl = ttl
        self.snapshot_every = snapshot_every
        self.track_paths = track_paths
        self.rng = np.random.default_rng(scenario.seed)

        self.nodes = sorted(graph.nodes)
        self.n_nodes = len(self.nodes)
        self.neighbors = neighbor_table(graph)
        self.hop_dist = hop_distances(graph)
        self.prop_dist = prop_distances(graph)
        self.links: dict[tuple[int, int], Link] = {}
        for u, v, d in graph.edges(data=True):
            for a, b in ((u, v), (v, u)):
                self.links[(a, b)] = Link(a, b, d["bw_mbps"], d["prop_ms"], d["queue_cap"])
        self.link_list = list(self.links.values())

        self.t = 0
        self.end_time = scenario.duration + scenario.drain
        self.calendar: dict[int, list[Packet]] = defaultdict(list)
        self.next_pid = 0
        self.in_network = 0

        # statistics (only packets created during [0, duration) exist)
        self.generated = 0
        self.generated_bytes = 0
        self.flow_generated: Counter = Counter()
        self.delivered = 0
        self.delivered_bytes = 0
        self.dropped_overflow = 0
        self.dropped_ttl = 0
        self.delays: list[int] = []
        self.flow_delays: dict[int, list[int]] = defaultdict(list)
        self.flow_paths: dict[int, Counter] = defaultdict(Counter)
        self.delivered_log: list[tuple] = []   # (t_created, t_delivered, flow, path, delay)
        self.total_hops = 0
        self.congestion_samples = 0
        self.congested_samples = 0
        self.ts_delivered = np.zeros(self.end_time, dtype=np.int32)
        self.ts_dropped = np.zeros(self.end_time, dtype=np.int32)
        self.ts_queued = np.zeros(self.end_time, dtype=np.int32)
        self.ts_delay_sum = np.zeros(self.end_time, dtype=np.float64)
        self.snapshots: list[Snapshot] = []
        self._snap_tx = {k: 0 for k in self.links}

        router.reset(self)

    # ------------------------------------------------------------------ events
    def _apply_events(self):
        if not self.scenario.events:
            return
        factor = {k: 1.0 for k in self.links}
        for ev in self.scenario.events:
            if ev.start <= self.t < ev.end:
                for key in ((ev.u, ev.v), (ev.v, ev.u)):
                    if key in factor:
                        factor[key] *= ev.factor
        for key, link in self.links.items():
            link.bw = link.bw_nominal * factor[key]

    # ------------------------------------------------------------------ packets
    def _deliver(self, pkt: Packet):
        self.in_network -= 1
        delay = self.t - pkt.t_created
        self.delivered += 1
        self.delivered_bytes += pkt.size
        self.delays.append(delay)
        self.flow_delays[pkt.flow].append(delay)
        self.total_hops += pkt.hops
        if self.track_paths:
            path = tuple(pkt.path)
            self.flow_paths[pkt.flow][path] += 1
            self.delivered_log.append((pkt.t_created, self.t, pkt.flow, path, delay))
        self.ts_delivered[self.t] += 1
        self.ts_delay_sum[self.t] += delay
        self.router.on_deliver(self, pkt)

    def _drop(self, pkt: Packet, reason: str, link: Link | None = None):
        self.in_network -= 1
        if reason == "overflow":
            self.dropped_overflow += 1
            if link is not None:
                link.drops += 1
                link.drop_ema += 0.2 * (1.0 - link.drop_ema)
        else:
            self.dropped_ttl += 1
        self.ts_dropped[self.t] += 1
        self.router.on_drop(self, pkt, reason)

    def _forward(self, pkt: Packet, nh: int):
        if pkt.hops >= self.ttl:
            self._drop(pkt, "ttl")
            return
        link = self.links.get((pkt.node, nh))
        if link is None:
            raise ValueError(f"router {self.router.name} chose non-neighbour {pkt.node}->{nh}")
        if len(link.queue) >= link.cap:
            self._drop(pkt, "overflow", link)
            return
        link.queue.append(pkt)
        link.queue_bytes += pkt.size
        pkt.hops += 1
        pkt.path.append(nh)

    def _generate(self) -> list[Packet]:
        new = []
        if self.t >= self.scenario.duration:
            return new
        load = self.scenario.load_at(self.t)
        for fid, flow in enumerate(self.scenario.flows):
            n = self.rng.poisson(flow.packets_per_ms(load))
            for _ in range(n):
                size = int(self.rng.integers(PKT_MIN_BYTES, PKT_MAX_BYTES + 1))
                pkt = Packet(self.next_pid, fid, flow.src, flow.dst, size, self.t)
                self.next_pid += 1
                self.generated += 1
                self.flow_generated[fid] += 1
                self.generated_bytes += size
                self.in_network += 1
                new.append(pkt)
        return new

    # ------------------------------------------------------------------ links
    def _serve_links(self):
        t = self.t
        in_window = t < self.scenario.duration
        for link in self.link_list:
            if in_window:
                link.bw_sum += link.bw
            link.tick_tx = 0
            if not link.queue:
                link.credit = 0.0
            else:
                link.credit += link.bw
                q = link.queue
                while q and link.credit >= q[0].size:
                    pkt = q.popleft()
                    link.credit -= pkt.size
                    link.queue_bytes -= pkt.size
                    link.tick_tx += pkt.size
                    pkt.node = link.v
                    self.calendar[t + link.prop].append(pkt)
                if in_window:
                    link.tx_bytes += link.tick_tx
                if not q:
                    link.credit = 0.0
            u = link.tick_tx / link.bw if link.bw > 0 else 1.0
            link.util_ema += 0.05 * (u - link.util_ema)
            link.drop_ema *= 0.98

    # ------------------------------------------------------------------ main loop
    def step(self):
        t = self.t
        self._apply_events()
        self.router.on_tick(self)

        waiting: list[Packet] = []
        for pkt in self.calendar.pop(t, ()):
            pkt.visited |= 1 << pkt.node
            if pkt.node == pkt.dst:
                self._deliver(pkt)
            else:
                waiting.append(pkt)
        waiting.extend(self._generate())

        if waiting:
            next_hops = self.router.choose(self, waiting)
            for pkt, nh in zip(waiting, next_hops):
                pkt.t_decision = t
                self._forward(pkt, nh)

        self._serve_links()

        queued = 0
        for link in self.link_list:
            n = len(link.queue)
            queued += n
            if t < self.scenario.duration:
                occ = n / link.cap
                link.occ_sum += occ
                self.congestion_samples += 1
                if occ >= CONGESTED_OCC:
                    link.congested_ticks += 1
                    self.congested_samples += 1
        self.ts_queued[t] = queued

        if self.snapshot_every and t % self.snapshot_every == 0:
            win = max(1, self.snapshot_every)
            util = {}
            for k, link in self.links.items():
                util[k] = (link.tx_bytes - self._snap_tx[k]) / (link.bw_nominal * win)
                self._snap_tx[k] = link.tx_bytes
            self.snapshots.append(Snapshot(
                t=t,
                occupancy={k: l.occupancy for k, l in self.links.items()},
                utilization=util,
                load=self.scenario.load_at(min(t, self.scenario.duration - 1)),
            ))
        self.t += 1

    def run(self):
        while self.t < self.end_time:
            self.step()
        self.router.on_episode_end(self)
        return self

    @property
    def in_flight(self) -> int:
        """Packets still queued or propagating (undelivered at the end)."""
        return self.in_network
